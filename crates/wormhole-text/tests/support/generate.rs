//! Writes `src/generated/keys.rs` and `files.rs` from the English files. No build script and no
//! macro that reads files: a test regenerates them, and fails (or, with `TEXT_BLESS=1`, rewrites
//! them) when the committed ones differ.

use std::collections::BTreeSet;
use std::fmt::Write as _;

use fluent_bundle::{FluentBundle, FluentResource};

use super::{languages, locales_dir, read_dir};

const HEADER: &str = "// @generated by tests/generated.rs from locales/: do not edit.\n\
                      // Rewrite with `TEXT_BLESS=1 cargo test -p wormhole-text --test generated`.\n";

/// Words a variable name cannot be, because it becomes a parameter name.
const KEYWORDS: [&str; 12] =
    ["as", "break", "fn", "for", "if", "in", "let", "loop", "match", "move", "ref", "type"];

pub struct Generated {
    pub ids: String,
    pub keys: String,
    pub files: String,
}

/// How a generated function takes one variable.
#[derive(Clone, Copy, PartialEq)]
enum Kind {
    Text,
    Number,
}

struct Function {
    id: String,
    index: usize,
    params: Vec<(String, String, Kind)>,
    source: String,
}

pub fn generate() -> Generated {
    let english = super::english();
    let en_files = read_dir(&locales_dir().join("en"));
    let docs = english_texts(&en_files);

    let mut ids = Vec::new();
    let mut takes_args = Vec::new();
    let mut constants = String::new();
    let mut functions = Vec::new();
    let mut names = BTreeSet::new();
    for (index, item) in english.messages.iter().enumerate() {
        let vars = english.variables(&item.id);
        ids.push(item.id.clone());
        takes_args.push(!vars.is_empty());
        let name = rust_name(&item.id);
        assert!(names.insert(name.clone()), "{}: another id makes the name {name}", item.id);
        if vars.is_empty() {
            let text = docs.iter().find(|(id, _)| *id == item.id).map(|(_, t)| t.as_str()).unwrap_or("");
            // `{:?}` keeps the doc on one line, however many lines the text has.
            let _ = write!(
                constants,
                "/// {text:?}\npub const {}: Key = Key::new({index});\n",
                name.to_uppercase()
            );
        } else {
            let params = vars
                .iter()
                .map(|var| {
                    let kind = if english.counted(&item.id, var) { Kind::Number } else { Kind::Text };
                    (var.clone(), param_name(&item.id, var), kind)
                })
                .collect();
            functions.push(Function { id: item.id.clone(), index, params, source: item.source.clone() });
        }
    }
    assert!(ids.len() < usize::from(u16::MAX), "a Key is a u16");

    let mut ids_file = String::from(HEADER);
    ids_file.push_str("//!\n//! The ids and which of them take variables; `keys.rs` names the places.\n\n");
    let _ = writeln!(
        ids_file,
        "/// Every message and attribute, in the order of the files; a `Key`'s index is a place here.\n\
         /// Each language's table is built by looking these ids up, never by position in a file.\n\
         pub const IDS: [&str; {}] = [",
        ids.len()
    );
    for id in &ids {
        let _ = writeln!(ids_file, "    {id:?},");
    }
    ids_file.push_str("];\n\n");
    let _ = writeln!(
        ids_file,
        "/// Whether the message at that place has variables: it is a function and has no `Key`.\n\
         pub(crate) const TAKES_ARGS: [bool; {}] = [",
        takes_args.len()
    );
    for flag in &takes_args {
        let _ = writeln!(ids_file, "    {flag},");
    }
    ids_file.push_str("];\n");

    let mut keys = String::from(HEADER);
    keys.push_str(
        "//!\n//! One constant per message without variables, one function per message with. The doc\n\
         //! comment of each is its English text.\n\n\
         use crate::args::Arg;\nuse crate::key::Key;\n\n",
    );
    keys.push_str(&constants);
    for function in &functions {
        keys.push('\n');
        keys.push_str(&render_function(function));
    }
    keys.push_str(&render_samples(&functions));

    Generated { ids: ids_file, keys, files: render_files() }
}

/// The English text of every message and attribute without variables, formatted.
fn english_texts(files: &[(String, String)]) -> Vec<(String, String)> {
    let mut bundle = FluentBundle::new(vec!["en".parse().unwrap_or_default()]);
    bundle.set_use_isolating(false);
    for (_, source) in files {
        let resource = FluentResource::try_new(source.clone()).unwrap_or_else(|(resource, _)| resource);
        let _ = bundle.add_resource(resource);
    }
    let english = super::english();
    let mut out = Vec::new();
    for item in &english.messages {
        if !english.variables(&item.id).is_empty() {
            continue;
        }
        let (name, attribute) = match item.id.split_once('.') {
            Some((name, attribute)) => (name, Some(attribute)),
            None => (item.id.as_str(), None),
        };
        let Some(message) = bundle.get_message(name) else { continue };
        let pattern = match attribute {
            Some(attribute) => message.get_attribute(attribute).map(|a| a.value()),
            None => message.value(),
        };
        if let Some(pattern) = pattern {
            let mut errors = Vec::new();
            out.push((item.id.clone(), bundle.format_pattern(pattern, None, &mut errors).into_owned()));
        }
    }
    out
}

fn rust_name(id: &str) -> String {
    id.replace(['-', '.'], "_")
}

fn param_name(id: &str, var: &str) -> String {
    let name = rust_name(var);
    assert!(!KEYWORDS.contains(&name.as_str()), "{id}: ${var} is a Rust keyword: rename the variable");
    name
}

fn render_function(function: &Function) -> String {
    let mut out = String::new();
    out.push_str("/// ```text\n");
    for line in function.source.lines() {
        let _ = writeln!(out, "/// {line}");
    }
    out.push_str("/// ```\n");
    let signature: Vec<String> = function
        .params
        .iter()
        .map(|(_, param, kind)| format!("{param}: {}", if *kind == Kind::Number { "i64" } else { "&str" }))
        .collect();
    let args: Vec<String> = function
        .params
        .iter()
        .map(|(var, param, kind)| {
            let arg = if *kind == Kind::Number { "Int" } else { "Str" };
            format!("({var:?}, Arg::{arg}({param}))")
        })
        .collect();
    let _ = writeln!(out, "pub fn {}({}) -> String {{", rust_name(&function.id), signature.join(", "));
    let _ = writeln!(out, "    crate::active::message({}, &[{}])", function.index, args.join(", "));
    out.push_str("}\n");
    out
}

/// Every function once with sample arguments (a number twice, one and many), for the tests that
/// look at all messages without knowing them: the pseudo-language's brackets, the translations.
fn render_samples(functions: &[Function]) -> String {
    let mut out = String::from(
        "\n/// Each message with variables formatted with sample arguments: text as `Sample`, numbers as 1 and\n\
         /// 5, so a plural shows both of English's forms.\n\
         #[cfg(feature = \"test-support\")]\n\
         pub fn samples() -> Vec<(&'static str, String)> {\n    vec![\n",
    );
    for function in functions {
        let counted = function.params.iter().any(|(_, _, kind)| *kind == Kind::Number);
        for number in if counted { vec![1, 5] } else { vec![1] } {
            let args: Vec<String> = function
                .params
                .iter()
                .map(
                    |(_, _, kind)| {
                        if *kind == Kind::Number { number.to_string() } else { "\"Sample\"".into() }
                    },
                )
                .collect();
            let _ = writeln!(
                out,
                "        ({:?}, {}({})),",
                function.id,
                rust_name(&function.id),
                args.join(", ")
            );
        }
    }
    out.push_str("    ]\n}\n");
    out
}

fn render_files() -> String {
    let tags = languages();
    assert_eq!(tags.first().map(String::as_str), Some("en"), "locales/en is the source language");
    let mut out = String::from(HEADER);
    out.push_str(
        "\n/// A language's files as the generator found them: `locales/<tag>/` and each `.ftl` in it.\n\
         pub(crate) struct Locale {\n\
         \x20   pub tag: &'static str,\n\
         \x20   /// `(file name, source)`, sorted by name.\n\
         \x20   pub files: &'static [(&'static str, &'static str)],\n\
         }\n\n",
    );
    out.push_str("/// English first, then the others by tag.\n");
    let _ = writeln!(out, "pub(crate) const LOCALES: [Locale; {}] = [", tags.len());
    for tag in &tags {
        let _ = writeln!(out, "    Locale {{\n        tag: {tag:?},\n        files: &[");
        for (name, _) in read_dir(&locales_dir().join(tag)) {
            let _ = writeln!(out, "            ({name:?}, include_str!(\"../../locales/{tag}/{name}\")),");
        }
        out.push_str("        ],\n    },\n");
    }
    out.push_str("];\n");
    out
}
