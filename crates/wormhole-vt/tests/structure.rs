//! The engine's structure rules, checked on every test run so they hold as it grows:
//! no file grows into an everything-module, and its layers only depend downwards
//! (`types` ← `unicode` ← `parser`, `grid` ← `terminal`), so each can be tested and replaced alone.

use std::fs;
use std::path::{Path, PathBuf};

/// A tripwire, not the target: files aim for ~600 lines with one responsibility each, and the
/// per-wave review judges anything above that. Only past this a file has clearly become several.
const MAX_LINES: usize = 1000;

/// Files allowed past the tripwire, each with the reason it is better whole (generated files, or a
/// piece that only reads well in one place). Add one here rather than splitting for the number.
const EXEMPT: &[(&str, &str)] = &[("src/unicode/tables.rs", "generated by scripts/gen-unicode.py")];

/// Each layer and the layers it must not reach into.
const LAYERS: &[(&str, &[&str])] = &[
    ("src/types", &["unicode", "parser", "grid", "terminal"]),
    ("src/unicode", &["parser", "grid", "terminal"]),
    ("src/parser", &["grid", "terminal"]),
    ("src/grid", &["parser", "terminal"]),
];

fn crate_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

fn rust_files(dir: &Path, out: &mut Vec<PathBuf>) {
    let Ok(entries) = fs::read_dir(dir) else { return };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            rust_files(&path, out);
        } else if path.extension().is_some_and(|ext| ext == "rs") {
            out.push(path);
        }
    }
}

fn relative(path: &Path) -> String {
    path.strip_prefix(crate_dir()).unwrap_or(path).to_string_lossy().replace('\\', "/")
}

#[test]
fn files_stay_under_the_length_limit() {
    let mut files = Vec::new();
    for dir in ["src", "tests", "examples", "benches"] {
        rust_files(&crate_dir().join(dir), &mut files);
    }
    let long: Vec<String> = files
        .iter()
        .filter(|path| !EXEMPT.iter().any(|(file, _)| *file == relative(path)))
        .filter_map(|path| {
            let lines = fs::read_to_string(path).ok()?.lines().count();
            (lines > MAX_LINES).then(|| format!("{} ({lines} lines)", relative(path)))
        })
        .collect();
    assert!(
        long.is_empty(),
        "these have grown into several files' worth (over {MAX_LINES} lines); split by responsibility: {long:#?}"
    );
}

/// A token of Rust source as far as the layer check cares: names and single punctuation marks.
#[derive(Debug, Clone, PartialEq, Eq)]
enum Token {
    Ident(String),
    Punct(char),
}

/// The names and punctuation of `source`, without comments, string and character literals (a
/// `crate::term` in a doc comment or a message is not a dependency).
fn tokens(source: &str) -> Vec<Token> {
    let chars: Vec<char> = source.chars().collect();
    let at = |i: usize| chars.get(i).copied().unwrap_or('\0');
    let mut out = Vec::new();
    let mut i = 0;
    while i < chars.len() {
        let c = chars[i];
        if c == '/' && at(i + 1) == '/' {
            while i < chars.len() && chars[i] != '\n' {
                i += 1;
            }
        } else if c == '/' && at(i + 1) == '*' {
            // Block comments nest in Rust.
            let mut depth = 0;
            while i < chars.len() {
                if at(i) == '/' && at(i + 1) == '*' {
                    depth += 1;
                    i += 2;
                } else if at(i) == '*' && at(i + 1) == '/' {
                    depth -= 1;
                    i += 2;
                    if depth == 0 {
                        break;
                    }
                } else {
                    i += 1;
                }
            }
        } else if c == '"' {
            i += 1;
            while i < chars.len() && chars[i] != '"' {
                i += if chars[i] == '\\' { 2 } else { 1 };
            }
            i += 1;
        } else if c == 'r' && matches!(at(i + 1), '"' | '#') && raw_string_end(&chars, i).is_some() {
            i = raw_string_end(&chars, i).unwrap_or(chars.len());
        } else if c == '\'' && (at(i + 1) == '\\' || at(i + 2) == '\'') {
            // A character literal; a lifetime has no closing quote.
            i += 2;
            while i < chars.len() && chars[i] != '\'' {
                i += 1;
            }
            i += 1;
        } else if c.is_alphabetic() || c == '_' {
            let start = i;
            while i < chars.len() && (chars[i].is_alphanumeric() || chars[i] == '_') {
                i += 1;
            }
            out.push(Token::Ident(chars[start..i].iter().collect()));
        } else {
            if !c.is_whitespace() {
                out.push(Token::Punct(c));
            }
            i += 1;
        }
    }
    out
}

/// Where the raw string starting at `start` (`r"…"`, `r#"…"#`) ends, if one starts there.
fn raw_string_end(chars: &[char], start: usize) -> Option<usize> {
    let hashes = chars[start + 1..].iter().take_while(|c| **c == '#').count();
    if chars.get(start + 1 + hashes) != Some(&'"') {
        return None;
    }
    let closing: Vec<char> = std::iter::once('"').chain(std::iter::repeat_n('#', hashes)).collect();
    let body = start + 2 + hashes;
    (body..chars.len()).find(|&i| chars[i..].starts_with(&closing)).map(|i| i + closing.len())
}

fn is_path_sep(tokens: &[Token], i: usize) -> bool {
    tokens.get(i) == Some(&Token::Punct(':')) && tokens.get(i + 1) == Some(&Token::Punct(':'))
}

/// The first names of the use tree starting at `i`, and where the tree ends: `grid::Cell` gives
/// `grid`, `{grid, parser::x}` gives both, however deep the groups nest.
fn tree_roots(tokens: &[Token], mut i: usize) -> (Vec<String>, usize) {
    let mut roots = Vec::new();
    match tokens.get(i) {
        Some(Token::Ident(name)) => {
            roots.push(name.clone());
            // The rest of the path (`::Cell`, `::{a, b}`, `as x`) up to the next `,` or `}`.
            let mut depth = 0;
            while let Some(token) = tokens.get(i) {
                match token {
                    Token::Punct('{') => depth += 1,
                    Token::Punct('}') if depth == 0 => break,
                    Token::Punct('}') => depth -= 1,
                    Token::Punct(',') | Token::Punct(';') if depth == 0 => break,
                    _ => {}
                }
                i += 1;
            }
        }
        Some(Token::Punct('{')) => {
            i += 1;
            while i < tokens.len() && tokens[i] != Token::Punct('}') {
                let (inner, end) = tree_roots(tokens, i);
                roots.extend(inner);
                i = end;
                if tokens.get(i) != Some(&Token::Punct(',')) {
                    break;
                }
                i += 1;
            }
            i += 1;
        }
        _ => {}
    }
    (roots, i)
}

/// The modules directly under the crate root that `source` names, through `crate::…` or through
/// enough `super::` to reach the root. `module` is where the file sits (`["grid", "page"]` for
/// `src/grid/page/mod.rs`); an inline `mod` inside the file is not counted, which can only hide a
/// `super::` that goes further up than it looks, never invent one.
fn root_modules(module: &[&str], source: &str) -> Vec<String> {
    let tokens = tokens(source);
    let mut found = Vec::new();
    for (i, token) in tokens.iter().enumerate() {
        let starts_path = i == 0 || !matches!(tokens[i - 1], Token::Punct(':') | Token::Punct('$'));
        match token {
            Token::Ident(name) if name == "crate" && starts_path && is_path_sep(&tokens, i + 1) => {
                found.extend(tree_roots(&tokens, i + 3).0);
            }
            Token::Ident(name) if name == "super" && starts_path => {
                let (mut ups, mut at) = (0, i);
                while tokens.get(at) == Some(&Token::Ident("super".to_string()))
                    && is_path_sep(&tokens, at + 1)
                {
                    ups += 1;
                    at += 3;
                }
                if ups >= module.len() {
                    found.extend(tree_roots(&tokens, at).0);
                }
            }
            _ => {}
        }
    }
    found
}

/// The module a file under `src/` defines: `grid/page/edit.rs` is `grid::page::edit`, a
/// `mod.rs` is its folder, and `lib.rs` is the root.
fn module_of(relative_to_src: &str) -> Vec<&str> {
    let mut parts: Vec<&str> = relative_to_src.trim_end_matches(".rs").split('/').collect();
    if parts.last().is_some_and(|last| *last == "mod" || *last == "lib") {
        parts.pop();
    }
    parts
}

#[test]
fn layers_only_depend_downwards() {
    let mut wrong = Vec::new();
    for (layer, forbidden) in LAYERS {
        let mut files = Vec::new();
        let dir = crate_dir().join(layer);
        rust_files(&dir, &mut files);
        let single = crate_dir().join(format!("{layer}.rs"));
        if single.exists() {
            files.push(single);
        }
        for path in files {
            let Ok(text) = fs::read_to_string(&path) else { continue };
            let file = relative(&path);
            let module = module_of(file.strip_prefix("src/").unwrap_or(&file));
            for root in root_modules(&module, &text) {
                if forbidden.contains(&root.as_str()) {
                    wrong.push(format!("{file} uses `{root}`"));
                }
            }
        }
    }
    assert!(wrong.is_empty(), "a layer reaches upwards: {wrong:#?}");
}

#[test]
fn the_layer_check_reads_use_trees_and_ignores_comments_and_strings() {
    let roots = |module: &[&str], source: &str| {
        let mut found = root_modules(module, source);
        found.sort();
        found
    };
    let names = |list: &[&str]| list.iter().map(|s| s.to_string()).collect::<Vec<_>>();
    // A brace group names several modules at once; this is what the textual check missed.
    assert_eq!(roots(&["types"], "use crate::{grid, parser};"), names(&["grid", "parser"]));
    assert_eq!(
        roots(&["types"], "use crate::{\n    types::{A, B},\n    grid::{self, Cell},\n};"),
        names(&["grid", "types"])
    );
    assert_eq!(roots(&["types"], "use crate::{a::{b, c::d}, e};"), names(&["a", "e"]));
    assert_eq!(roots(&["types"], "use crate::{{grid}, parser};"), names(&["grid", "parser"]));
    assert_eq!(roots(&["types"], "let x = crate::term::Term::new();"), names(&["term"]));
    assert_eq!(roots(&["types"], "pub(in crate::grid) fn f() {}"), names(&["grid"]));
    // `pub(crate)` and `$crate` are not paths into a module.
    assert!(roots(&["types"], "pub(crate) fn f() {} $crate::term").is_empty());
    // Comments, doc comments, strings and characters do not count.
    let quiet = "// use crate::term;\n/// see `crate::grid`\n/* crate::parser /* crate::term */ */\n\
                 let s = \"crate::term\"; let r = r#\"crate::{grid}\"#; let c = '\\''; fn f<'a>() {}";
    assert!(roots(&["types"], quiet).is_empty(), "{:?}", roots(&["types"], quiet));
    // `super::` counts only when it climbs to the crate root.
    assert!(roots(&["grid", "page", "edit"], "use super::super::term;").is_empty());
    assert_eq!(roots(&["grid", "page", "edit"], "use super::super::super::term;"), names(&["term"]));
    assert_eq!(roots(&["grid"], "use super::{term, types};"), names(&["term", "types"]));
    assert!(roots(&["grid", "row"], "use super::cell::Cell; use self::row::Row;").is_empty());
    // A name that merely contains a layer's is not it.
    assert!(roots(&["types"], "use crate::terminal_size;").iter().all(|r| r != "term"));
}

