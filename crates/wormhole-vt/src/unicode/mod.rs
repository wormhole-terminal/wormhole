//! Cell widths and grapheme cluster breaks, from tables generated for Unicode 18.
//!
//! - [`width`]: how many cells a character takes (0, 1 or 2). Printable ASCII, nearly all of what a
//!   terminal prints, never reaches a table.
//! - [`breaks`] and [`GraphemeState`]: the extended grapheme cluster boundaries of UAX #29, one
//!   character at a time, for mode 2027 (a cluster is one cell group). [`GraphemeState::step`] answers
//!   the break and the width together, with one lookup.
//! - [`extend_width`] and [`cluster_width`]: how wide a cluster is, where an emoji variation
//!   selector or a combining mark joins a base character.
//!
//! `tables.rs` is generated by `scripts/gen-unicode.py`; every property of a code point is one byte
//! of a three-stage table, so a lookup is three loads and no search.

mod grapheme;
mod tables;
mod width;

pub use grapheme::{GraphemeState, Step, breaks};
pub use tables::UNICODE_VERSION;
pub use width::{cluster_width, extend_width, has_emoji_variation, width};
