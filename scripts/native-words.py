#!/usr/bin/env python3
"""Make the native Settings window's Fluent messages and key table from its word list.

Input:  crates/wormhole/src/settings_window/native/words.txt (English, one word per line).
Output: crates/wormhole-text/locales/en/settings-native.ftl and native/words_table.rs.
The id of a word is `native-<slug>-<fnv1a hex>`; the window computes the same id (Store.swift `wordID`).
Then: TEXT_BLESS=1 cargo test -p wormhole-text --test generated
"""
import re
from pathlib import Path

root = Path(__file__).resolve().parent.parent
src = root / "crates/wormhole/src/settings_window/native"


def word_id(english: str) -> str:
    h = 0x811C9DC5
    for b in english.encode("utf-8"):
        h = ((h ^ b) * 0x01000193) & 0xFFFFFFFF
    slug = re.sub(r"[^a-z0-9]+", "-", english.lower()[:40]).strip("-")
    return f"native-{slug}-{h:08x}" if slug else f"native-{h:08x}"


def ftl_value(english: str) -> str:
    # Fluent reads `{` and `}` as placeables; leading `[`, `*` or `.` of a line would start syntax.
    return re.sub(r"[{}]", lambda m: '{ "%s" }' % m.group(0), english)


words = [w for w in (src / "words.txt").read_text().splitlines() if w and not w.startswith("#")]
ids = {}
for w in words:
    i = word_id(w)
    assert ids.setdefault(i, w) == w, f"id clash: {i}"

ftl = ["# The native Settings window's words (SwiftUI, behind `native_settings`), one message per word it shows that",
       "# its own catalog owns. Generated by scripts/native-words.py from native/words.txt; a `%@` is where the window",
       "# puts a value.", ""]
table = ["//! The native window's words, by id: generated by `scripts/native-words.py` from `words.txt`.", "",
         "use wormhole_text::{Key, keys};", "",
         "pub(super) const WORDS: &[(&str, Key)] = &["]
for i, w in ids.items():
    ftl.append(f"{i} = {ftl_value(w)}")
    table.append(f'    ("{i}", keys::{i.upper().replace("-", "_")}),')
table.append("];")
(root / "crates/wormhole-text/locales/en/settings-native.ftl").write_text("\n".join(ftl) + "\n")
(src / "words_table.rs").write_text("\n".join(table) + "\n")
print(len(ids), "words")
