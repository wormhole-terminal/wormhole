#!/bin/bash
# Prepare an existing git worktree for parallel work (several agents or tasks at once) so it can
# share ONE cargo target directory with the main checkout without the builds corrupting each other.
#
#   git worktree add .claude/worktrees/<name> -b <branch> <base>     # create it (not done here)
#   scripts/worktree.sh .claude/worktrees/<name>                      # write its .cargo/config.toml
#   cd .claude/worktrees/<name> && export CARGO_TARGET_DIR=<main checkout>/target
#
# Why the generated .cargo/config.toml matters:
# - Cargo hashes workspace crates by their workspace-relative path, so every worktree gets the SAME
#   unit hash for wormhole-core, wormhole-term and wormhole. Sharing a target dir then lets one worktree's
#   build be linked into another's (false green or red). A distinct, harmless codegen-units value
#   per worktree gives each its own hash; third-party dependencies keep theirs and stay shared.
# - `strip` must be repeated in each package table (a package with its own table does not inherit
#   [profile.dev] strip). ~93% of a linked test binary is DWARF; stripping shrinks executables ~14x.
# Run cargo with the worktree as the CURRENT directory: config discovery uses the cwd.
set -euo pipefail

path="${1:?usage: scripts/worktree.sh <worktree path>   e.g. .claude/worktrees/<name>}"
[ -d "$path" ] || { echo "error: $path is not a directory (create it with git worktree add first)" >&2; exit 1; }
dir="$(cd "$path" && pwd -P)"
# A worktree has a .git file (a plain checkout has a directory); either way it must be a work tree root.
[ -e "$dir/.git" ] && [ "$(git -C "$dir" rev-parse --show-toplevel)" = "$dir" ] \
  || { echo "error: $dir is not the root of a git worktree" >&2; exit 1; }
root="$(git -C "$dir" worktree list --porcelain | sed -n '1s/^worktree //p')"   # the main checkout
[ "$dir" != "$root" ] || { echo "error: $dir is the main checkout; pass a linked worktree" >&2; exit 1; }

# A stable value in 40..239 derived from the path, bumped past any value another worktree uses.
n=$(( $(printf '%s' "$dir" | cksum | cut -d' ' -f1) % 200 + 40 ))
used=""
while IFS= read -r wt; do
  [ "$wt" = "$dir" ] && continue
  used="$used
$(grep -hs '^codegen-units' "$wt/.cargo/config.toml" 2>/dev/null | grep -oE '[0-9]+' || true)"
done < <(git -C "$dir" worktree list --porcelain | sed -n 's/^worktree //p')
while grep -qx "$n" <<<"$used"; do n=$(( (n - 40 + 1) % 200 + 40 )); done

mkdir -p "$dir/.cargo"
cat > "$dir/.cargo/config.toml" <<TOML
# Per-worktree build identity (generated by scripts/worktree.sh; never commit this file).
[profile.dev]
strip = "debuginfo"

[profile.dev.package.wormhole-core]
codegen-units = $n
strip = "debuginfo"

[profile.dev.package.wormhole-term]
codegen-units = $n
strip = "debuginfo"

[profile.dev.package.wormhole]
codegen-units = $n
strip = "debuginfo"
TOML

# Keep the generated file out of commits (shared by all worktrees of this repository).
exclude="$(git -C "$dir" rev-parse --git-common-dir)/info/exclude"
grep -qx '/.cargo/config.toml' "$exclude" 2>/dev/null || printf '/.cargo/config.toml\n' >> "$exclude"

echo "prepared: $dir (build identity codegen-units=$n)"
echo "use:      cd $dir && export CARGO_TARGET_DIR=$root/target"
echo "warning:  \$CARGO_TARGET_DIR/debug/Wormhole is shared by every worktree using that dir: copy the" >&2
echo "          binary somewhere private before running it for devctl (see the devctl skill)." >&2
