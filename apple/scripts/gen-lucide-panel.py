#!/usr/bin/env python3
"""Writes swift/Sources/DesignSystem/Icons/LucidePanelData.swift: the Lucide icons the right panel draws (the ones its
GPUI views take from gpui-kit-assets' `IconName`), as SVG path data in their 24-point box.

    python3 apple/scripts/gen-lucide-panel.py <gpui-kit-assets>/assets/icons

Circles, lines, polylines and rectangles are written as paths (arcs and lines), as the sidebar's icons are.
"""
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

# Swift case name -> Lucide file name (without .svg).
ICONS = {
    "chevronLeft": "chevron-left", "chevronRight": "chevron-right", "chevronDown": "chevron-down",
    "chevronsUpDown": "chevrons-up-down", "x": "x", "plus": "plus", "copy": "copy", "check": "check",
    "refreshCw": "refresh-cw", "slidersHorizontal": "sliders-horizontal", "textWrap": "text-wrap",
    "externalLink": "external-link", "inbox": "inbox", "file": "file", "fileText": "file-text",
    "filePlus": "file-plus", "info": "info", "shield": "shield", "shieldCheck": "shield-check",
    "triangleAlert": "triangle-alert", "arrowUpRight": "arrow-up-right", "arrowRight": "arrow-right",
    "play": "play", "ellipsis": "ellipsis", "messageSquarePlus": "message-square-plus", "ban": "ban",
}


def num(value):
    return ("%g" % float(value))


def circle(cx, cy, r):
    return f"M{num(cx - r)} {num(cy)}a{num(r)} {num(r)} 0 1 0 {num(2 * r)} 0a{num(r)} {num(r)} 0 1 0 {num(-2 * r)} 0"


def rect(x, y, w, h, rx):
    rx = min(rx, w / 2, h / 2)
    if rx == 0:
        return f"M{num(x)} {num(y)}h{num(w)}v{num(h)}h{num(-w)}z"
    return (f"M{num(x + rx)} {num(y)}h{num(w - 2 * rx)}a{num(rx)} {num(rx)} 0 0 1 {num(rx)} {num(rx)}v{num(h - 2 * rx)}"
            f"a{num(rx)} {num(rx)} 0 0 1 {num(-rx)} {num(rx)}h{num(-(w - 2 * rx))}a{num(rx)} {num(rx)} 0 0 1 {num(-rx)} {num(-rx)}"
            f"v{num(-(h - 2 * rx))}a{num(rx)} {num(rx)} 0 0 1 {num(rx)} {num(-rx)}z")


def paths(svg):
    out = []
    for el in ET.parse(svg).getroot().iter():
        tag = el.tag.split("}")[-1]
        a = el.attrib
        if tag == "path":
            out.append(a["d"])
        elif tag == "circle":
            out.append(circle(float(a["cx"]), float(a["cy"]), float(a["r"])))
        elif tag == "line":
            out.append(f"M{a['x1']} {a['y1']}L{a['x2']} {a['y2']}")
        elif tag in ("polyline", "polygon"):
            points = re.findall(r"-?[\d.]+", a["points"])
            pairs = [f"{points[i]} {points[i + 1]}" for i in range(0, len(points), 2)]
            out.append("M" + "L".join(pairs) + ("z" if tag == "polygon" else ""))
        elif tag == "rect":
            out.append(rect(float(a.get("x", 0)), float(a.get("y", 0)), float(a["width"]), float(a["height"]), float(a.get("rx", 0))))
        elif tag == "ellipse":
            raise SystemExit(f"{svg}: an ellipse needs its own arc form")
    return out


def main():
    icons = Path(sys.argv[1])
    lines = ["// Generated by scripts/gen-lucide-panel.py from gpui-kit-assets' Lucide icons: the strokes the right panel's views draw,",
             "// as SVG path data in their 24-point box (stroke width 2, round caps and joins).", "", "extension Lucide {",
             "    static let panelDrawings: [Lucide: [String]] = ["]
    for case, name in ICONS.items():
        data = ", ".join('"%s"' % d.replace("\\", "\\\\") for d in paths(icons / f"{name}.svg"))
        lines.append(f"        .{case}: [{data}],")
    lines += ["    ]", "}", ""]
    target = Path(__file__).resolve().parents[1] / "swift/Sources/DesignSystem/Icons/LucidePanelData.swift"
    target.write_text("\n".join(lines))
    print(f"wrote {target} ({len(ICONS)} icons)")


main()
