#!/usr/bin/env python3
"""Feature parity tracker for the Swift UI against the GPUI app (see apple/parity/README.md).

    python3 -I apple/scripts/parity.py              overall, per area, ten heaviest gaps, feature counts
    python3 -I apple/scripts/parity.py --markdown   the same as Markdown for a status report
    python3 -I apple/scripts/parity.py --size       Swift lines per module against the GPUI app's lines
    python3 -I apple/scripts/parity.py --check      validate the CSV only (exit 1 on any problem)
    python3 -I apple/scripts/parity.py --selftest   run the built-in tests

Standard library only. Reads apple/parity/features.csv and, for --size, apple/swift/Sources.
"""

import csv
import io
import os
import sys
import unittest

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CSV_PATH = os.path.join(ROOT, "apple", "parity", "features.csv")
SOURCES = os.path.join(ROOT, "apple", "swift", "Sources")

AREAS = ["terminal", "sidebar", "window", "panel", "overlays", "platform", "aux", "settings", "studio", "crosscut"]
LOOKS = (0.0, 0.25, 0.5, 0.75, 1.0)
WORKS = (0.0, 0.5, 1.0)
COLUMNS = ["id", "area", "feature", "weight", "looks", "works_mock", "works_real", "works", "wired", "evidence", "owner", "notes"]
WIRED = ("yes", "part", "no")
# The app crate's production Rust lines (inventory section 1.1): the size the Swift shell is measured against.
GPUI_PRODUCTION_LINES = 121_651
# Generated by UniFFI; not written by hand and gone when the model moves behind a smaller seam.
GENERATED_MODULES = {"WormholeBindings"}
LOOKS_THRESHOLD = 0.75  # "looks done" for the unweighted count
WORKS_THRESHOLD = 0.5   # "works done" for the unweighted count


class Feature(object):
    def __init__(self, row):
        self.id = row["id"]
        self.area = row["area"]
        self.name = row["feature"]
        self.weight = int(row["weight"])
        # A blank looks means nothing visual to match (a keyboard encoder): left out of the looks figures.
        self.looks = float(row["looks"]) if row["looks"] != "" else None
        self.mock = float(row["works_mock"])
        self.real = float(row["works_real"])
        self.works = float(row["works"])
        self.wired = row["wired"]
        self.evidence = row["evidence"]
        self.owner = row["owner"]
        self.notes = row["notes"]

    @property
    def gap(self):
        """Weight not yet done: the mean of looks and works_real (when it has a look), taken from the weight."""
        grades = [g for g in (self.looks, self.real) if g is not None]
        return self.weight * (1 - sum(grades) / len(grades))


def combined(mock, real, wired):
    """works: the real grade, or 0.5 for a feature that runs on samples in the app (a module nothing opens counts 0)."""
    return max(real, 0.5 if (mock > 0 and wired != "no") else 0.0)


def parse(text):
    """Return (features, problems) from the CSV text. Problems are strings; features are the valid rows."""
    problems = []
    reader = csv.DictReader(io.StringIO(text))
    if reader.fieldnames != COLUMNS:
        return [], ["header must be exactly: " + ",".join(COLUMNS)]
    seen = set()
    features = []
    for number, row in enumerate(reader, start=2):
        where = "line %d (%s)" % (number, row.get("id"))
        if None in row or any(value is None for value in row.values()):
            problems.append("%s: wrong number of columns (a comma inside a field? use a semicolon)" % where)
            continue
        before = len(problems)
        if not row["id"] or row["id"] in seen:
            problems.append("%s: id missing or duplicated" % where)
        seen.add(row["id"])
        if row["area"] not in AREAS:
            problems.append("%s: area %r not in %s" % (where, row["area"], AREAS))
        if not row["feature"]:
            problems.append("%s: empty feature" % where)
        try:
            if int(row["weight"]) <= 0:
                problems.append("%s: weight must be positive" % where)
        except ValueError:
            problems.append("%s: weight %r is not an integer" % (where, row["weight"]))
        if row["wired"] not in WIRED:
            problems.append("%s: wired %r is not one of %s" % (where, row["wired"], WIRED))
        for column, allowed in (("looks", LOOKS), ("works_mock", WORKS), ("works_real", WORKS), ("works", WORKS)):
            value = row[column]
            if value == "" and column == "looks":
                continue
            try:
                if float(value) not in allowed:
                    problems.append("%s: %s %s is not one of %s" % (where, column, value, allowed))
            except ValueError:
                problems.append("%s: %s %r is not a number" % (where, column, value))
        if len(problems) == before:
            feature = Feature(row)
            graded = max(feature.mock, feature.real) > 0 or (feature.looks or 0) > 0
            if graded and not feature.evidence.strip():
                problems.append("%s: a graded row needs evidence" % where)
            if feature.wired == "no" and feature.real > 0:
                problems.append("%s: a feature nothing in the app opens cannot be works_real" % where)
            if feature.works != combined(feature.mock, feature.real, feature.wired):
                problems.append("%s: works must be %s (real, else 0.5 for wired mock)" % (where, combined(feature.mock, feature.real, feature.wired)))
            features.append(feature)
    return features, problems


def missing_evidence(features, root=ROOT):
    """Evidence paths under apple/ that do not exist (png: entries name scratchpad renders and are not checked)."""
    missing = []
    for feature in features:
        for item in [part.strip() for part in feature.evidence.split(";") if part.strip()]:
            if item.startswith("apple/") and not os.path.exists(os.path.join(root, item)):
                missing.append("%s: evidence %s does not exist" % (feature.id, item))
    return missing


def percent(numerator, denominator):
    return 100.0 * numerator / denominator if denominator else 0.0


def totals(features):
    """Weighted percentages over a list of features: looks, works_real, works_mock, works (combined)."""
    visual = [f for f in features if f.looks is not None]
    weight = sum(f.weight for f in features)
    looks = percent(sum(f.weight * f.looks for f in visual), sum(f.weight for f in visual))
    real = percent(sum(f.weight * f.real for f in features), weight)
    mock = percent(sum(f.weight * f.mock for f in features), weight)
    both = percent(sum(f.weight * f.works for f in features), weight)
    return looks, real, mock, both


def by_area(features):
    rows = []
    for area in AREAS:
        group = [f for f in features if f.area == area]
        if group:
            rows.append((area, len(group), sum(f.weight for f in group)) + totals(group))
    return rows


def heaviest_gaps(features, count=10):
    return sorted(features, key=lambda f: (-f.gap, f.id))[:count]


def counts(features):
    visual = [f for f in features if f.looks is not None]
    return (
        sum(1 for f in visual if f.looks >= LOOKS_THRESHOLD), len(visual),
        sum(1 for f in features if f.real >= WORKS_THRESHOLD), sum(1 for f in features if f.works >= WORKS_THRESHOLD),
        len(features),
    )


def swift_lines(sources=SOURCES):
    """Swift lines per module (a folder under Sources), without the generated bindings."""
    modules = {}
    for module in sorted(os.listdir(sources)):
        folder = os.path.join(sources, module)
        if not os.path.isdir(folder) or module in GENERATED_MODULES:
            continue
        total = 0
        for directory, _, names in os.walk(folder):
            for name in names:
                if name.endswith(".swift"):
                    with open(os.path.join(directory, name), encoding="utf-8") as handle:
                        total += sum(1 for _ in handle)
        modules[module] = total
    return modules


def report(features, markdown):
    looks, real, mock, both = totals(features)
    weight = sum(f.weight for f in features)
    looks_n, looks_of, real_n, both_n, n = counts(features)
    lines = []
    emit = lines.append
    unweighted = ("Unweighted: looks >= %.2f on %d of %d visual features; works_real >= %.1f on %d of %d; "
                  "works (combined) >= %.1f on %d of %d." % (LOOKS_THRESHOLD, looks_n, looks_of, WORKS_THRESHOLD, real_n, n, WORKS_THRESHOLD, both_n, n))
    if markdown:
        emit("**Parity** (%d features, %s GPUI lines weighted): **looks %.1f %%**, **works_real %.1f %%**, works_mock %.1f %%, works combined %.1f %%"
             % (n, format(weight, ","), looks, real, mock, both))
        emit("")
        emit("| Area | Features | Weight | Looks | Real | Mock | Combined |")
        emit("|---|--:|--:|--:|--:|--:|--:|")
        for area, count, w, lk, re_, mo, bo in by_area(features):
            emit("| %s | %d | %s | %.1f %% | %.1f %% | %.1f %% | %.1f %% |" % (area, count, format(w, ","), lk, re_, mo, bo))
        emit("")
        emit(unweighted)
        emit("")
        emit("| Heaviest gaps | Area | Weight | Looks | Real | Mock | Wired |")
        emit("|---|---|--:|--:|--:|--:|---|")
        for f in heaviest_gaps(features):
            emit("| %s %s | %s | %s | %s | %s | %s | %s |" % (f.id, f.name, f.area, format(f.weight, ","), "-" if f.looks is None else f.looks, f.real, f.mock, f.wired))
    else:
        emit("Parity over %d features, %s GPUI production lines of weight" % (n, format(weight, ",")))
        emit("  LOOKS %5.1f %%   WORKS_REAL %5.1f %%   works_mock %5.1f %%   works combined %5.1f %%" % (looks, real, mock, both))
        emit("")
        emit("%-10s %4s %8s %7s %7s %7s %9s" % ("area", "n", "weight", "looks", "real", "mock", "combined"))
        for area, count, w, lk, re_, mo, bo in by_area(features):
            emit("%-10s %4d %8s %6.1f%% %6.1f%% %6.1f%% %8.1f%%" % (area, count, format(w, ","), lk, re_, mo, bo))
        emit("")
        emit(unweighted)
        emit("")
        emit("The 10 heaviest gaps (weight not yet done, from looks and works_real)")
        for f in heaviest_gaps(features):
            emit("  %-5s %7s lines  looks %-4s real %-3s mock %-3s wired %-4s %s"
                 % (f.id, format(int(f.gap), ","), "-" if f.looks is None else f.looks, f.real, f.mock, f.wired, f.name))
    return "\n".join(lines)


def size_report(features, modules, markdown):
    total = sum(modules.values())
    _, real, _, both = totals(features)
    ratio = total / float(GPUI_PRODUCTION_LINES)
    lines = []
    emit = lines.append
    if markdown:
        emit("| Swift module | Lines |")
        emit("|---|--:|")
        for name, count in sorted(modules.items(), key=lambda item: -item[1]):
            emit("| %s | %s |" % (name, format(count, ",")))
        emit("| **total (no generated bindings)** | **%s** |" % format(total, ","))
        emit("")
    else:
        for name, count in sorted(modules.items(), key=lambda item: -item[1]):
            emit("%-16s %7s" % (name, format(count, ",")))
        emit("%-16s %7s   (generated bindings excluded)" % ("total", format(total, ",")))
    emit("Swift %s lines against %s GPUI app production lines: %.1f %% of the size." % (format(total, ","), format(GPUI_PRODUCTION_LINES, ","), 100 * ratio))
    if both > 0:
        # Naive on purpose: the cheap rows may be the ones done first, so this under-states the finished size.
        # It counts the combined works share, because a merged but unwired module is code that exists and is paid for
        # in lines; the real share would charge those lines to too small a base.
        emit("Naive linear projection at works 100 %%: about %s lines (%.1f %% of GPUI). Not a forecast: the done rows are the cheap ones."
             % (format(int(total * 100 / both), ","), 100 * total * 100 / both / GPUI_PRODUCTION_LINES))
    return "\n".join(lines)


SAMPLE = """id,area,feature,weight,looks,works_mock,works_real,works,wired,evidence,owner,notes
A,terminal,First,100,1,0,1,1,yes,apple/x,,
B,terminal,Second,300,0.5,1,0,0.5,yes,apple/y,,
C,sidebar,Third,100,,0,0,0,no,,,
D,panel,Unwired,100,0.5,1,0,0,no,apple/z,,
"""


class Tests(unittest.TestCase):
    def test_totals_weight_and_skip_blank_looks(self):
        features, problems = parse(SAMPLE)
        self.assertEqual(problems, [])
        looks, real, mock, both = totals(features)
        self.assertAlmostEqual(looks, (100 * 1 + 300 * 0.5 + 100 * 0.5) / 500 * 100)
        self.assertAlmostEqual(real, 100 / 600.0 * 100)
        self.assertAlmostEqual(mock, 400 / 600.0 * 100)
        self.assertAlmostEqual(both, (100 + 150) / 600.0 * 100)

    def test_gap_uses_looks_and_real(self):
        features, _ = parse(SAMPLE)
        self.assertEqual([f.gap for f in features], [0.0, 225.0, 100.0, 75.0])
        self.assertEqual(heaviest_gaps(features, 1)[0].id, "B")

    def test_counts(self):
        features, _ = parse(SAMPLE)
        self.assertEqual(counts(features), (1, 3, 1, 2, 4))

    def test_validation(self):
        bad = SAMPLE + "A,terminal,Dup,10,1,0,1,1,yes,e,,\nE,nowhere,Area,10,1,0,1,1,yes,e,,\nF,panel,Weight,0,1,0,1,1,yes,e,,\n"
        bad += "G,panel,Grade,10,0.3,0,1,1,yes,e,,\nH,panel,Real,10,1,0,0.25,0.25,yes,e,,\nI,panel,NoEvidence,10,1,0,1,1,yes,,,\n"
        bad += "J,panel,Cols,10,1,0,1,1,yes,e,,x,y\nK,panel,Unwired real,10,1,0,1,1,no,e,,\nL,panel,Combined,10,1,1,0,1,yes,e,,\nM,panel,Wired,10,1,0,1,1,maybe,e,,\n"
        _, problems = parse(bad)
        text = "\n".join(problems)
        for needle in ("duplicated", "area", "positive", "looks 0.3", "works_real 0.25", "needs evidence", "columns",
                       "cannot be works_real", "works must be", "wired"):
            self.assertIn(needle, text)

    def test_header_must_match(self):
        self.assertTrue(parse("id,area\n1,2\n")[1])

    def test_shipped_csv_is_valid(self):
        with open(CSV_PATH, encoding="utf-8", newline="") as handle:
            features, problems = parse(handle.read())
        self.assertEqual(problems, [])
        self.assertEqual(missing_evidence(features), [])


def main(argv):
    if "--selftest" in argv:
        return 0 if unittest.main(argv=[argv[0]], exit=False).result.wasSuccessful() else 1
    with open(CSV_PATH, encoding="utf-8", newline="") as handle:
        features, problems = parse(handle.read())
    problems += missing_evidence(features)
    if problems:
        sys.stderr.write("\n".join(problems) + "\n")
        return 1
    markdown = "--markdown" in argv
    if "--check" in argv:
        print("ok: %d features" % len(features))
    elif "--size" in argv:
        print(size_report(features, swift_lines(), markdown))
    else:
        print(report(features, markdown))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
