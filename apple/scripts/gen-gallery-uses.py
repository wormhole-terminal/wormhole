#!/usr/bin/env python3
"""Writes `StudioUI/Gallery/GalleryUses.swift`: which theme tokens each component of the Theme Studio's gallery draws
with, read from the Swift sources themselves, so "Used by" and the outline in the gallery cannot drift from what the
views really use.

    python3 -I apple/scripts/gen-gallery-uses.py [--check]

A component is a set of source files (SPECIMENS). A token is found as an accessor of the generated `ThemeTokens`
(`tokens.sidebarRowSelected`), a `Palette` reader (which names the accessor it forwards to), a `named: "x"` string,
or a corner and rule role (`Radius.card`, `Rule.border`). `--check` changes nothing and fails when the file is stale.
"""
import re
import sys
from fnmatch import fnmatch
from pathlib import Path

SWIFT = Path(__file__).resolve().parents[1] / "swift/Sources"
OUT = SWIFT / "StudioUI/Gallery/GalleryUses.swift"

SPECIMENS = {
    "sidebar": ["SidebarUI/*"],
    "notes": ["PanelUI/Note*", "PanelUI/Task*", "PanelUI/Steps*", "PanelUI/PanelCard*"],
    "changes": ["PanelUI/Change*", "PanelUI/File*", "PanelUI/Branch*", "PanelUI/Band*", "PanelUI/Card*",
                "PanelUI/Disclosure*", "PanelUI/RowSurface*", "PanelUI/LineCounts*"],
    "history": ["PanelUI/Commit*", "PanelUI/History*"],
    "diff": ["PanelUI/Diff*"],
    "palette": ["PaletteUI/*"],
    "fonts": ["FontPickerUI/*"],
    "find": ["TerminalUI/Find/*"],
    "panes": ["PanesUI/Panes/*"],
    "tiles": ["PanesUI/Panes/TerminalTile*", "PanesUI/Tabs/*"],
    "chips": ["PanesUI/Title/*"],
    "labels": ["StudioUI/Gallery/LabelsSpecimen.swift", "DesignSystem/SectionLabel.swift"],
    "buttons": ["AuxWindows/Shared/AuxButtons.swift"],
    "windows": ["AuxWindows/Shared/AuxCard.swift", "AuxWindows/Shared/StatusBadge.swift", "AuxWindows/Hosts/HostCardView.swift"],
    "chrome": ["DesignSystem/IconButton.swift", "DesignSystem/CountBadge.swift", "DesignSystem/StatusDot.swift",
               "DesignSystem/SectionLabel.swift", "DesignSystem/Row.swift"],
}
ROLES = {"Radius.sm": "metrics.radius_sm", "Radius.chip": "metrics.radius_chip", "Radius.control": "metrics.radius",
         "Radius.card": "metrics.radius_lg", "Rule.border": "metrics.border_width",
         "Rule.divider": "metrics.divider_width", "Rule.focusRing": "metrics.focus_ring_width"}


def accessors() -> dict[str, str]:
    table: dict[str, str] = {}
    for name in ("Tokens1.swift", "Tokens2.swift"):
        text = (SWIFT / "DesignSystem/Theme" / name).read_text()
        table.update({a: t for a, t in re.findall(r'public var (\w+): Color \{ color\(named: "([^"]+)"\) \}', text)})
    palette = (SWIFT / "DesignSystem/Scale/Palette.swift").read_text()
    for name, accessor in re.findall(r"public static var (\w+): Color \{ tokens\.(\w+) \}", palette):
        if accessor in table:
            table[name] = table[accessor]
    return table


def tokens_of(text: str, table: dict[str, str]) -> set[str]:
    found = {table[m] for m in re.findall(r"\b(?:tokens|Palette|ui)\.(\w+)", text) if m in table}
    found |= set(re.findall(r'(?:named|rgba\(named): "([a-z_.0-9]+)"', text))
    found |= {token for role, token in ROLES.items() if role in text}
    return found


def main() -> int:
    table = accessors()
    lines = ["// Generated by apple/scripts/gen-gallery-uses.py from the Swift sources: do not edit.",
             "// The tokens each gallery component's views draw with, which the Studio outlines and lists as \"Used by\".",
             "", "enum GalleryUses {"]
    for name, patterns in SPECIMENS.items():
        files = sorted(p for p in SWIFT.glob("*/**/*.swift") if any(fnmatch(str(p.relative_to(SWIFT)), g) for g in patterns))
        tokens = sorted(set().union(*(tokens_of(f.read_text(), table) for f in files)))
        lines.append(f"    static let {name}: [String] = [")
        lines += [f'        "{t}",' for t in tokens]
        lines.append("    ]")
    lines += ["}", ""]
    text = "\n".join(lines)
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("GalleryUses.swift is stale: run apple/scripts/gen-gallery-uses.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    print({n: len([l for l in text.split(f"static let {n}: [String] = [")[1].split("]")[0].splitlines() if l.strip()]) for n in SPECIMENS})
    return 0


if __name__ == "__main__":
    sys.exit(main())
