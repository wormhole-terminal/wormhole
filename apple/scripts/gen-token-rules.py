#!/usr/bin/env python3
"""Writes `StudioModel/Tokens/CoreRules.swift`: every token's default derivation rule, as the Theme Studio's
"Rule" section shows it, read from `wormhole-core`'s `theme/tokens/rules.rs`.

    python3 -I apple/scripts/gen-token-rules.py [--check]

This is a stand-in for an FFI call (`default_rule`), which would need no file at all: it reads the rule
table's text, so it stops at a line it does not understand (and says which) rather than guess. `--check`
changes nothing and fails when the Swift file is out of date.
"""
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SOURCE = REPO / "crates/wormhole-core/src/theme/tokens/rules.rs"
OUT = REPO / "apple/swift/Sources/StudioModel/Tokens/CoreRules.swift"

STRING = r'"((?:[^"\\]|\\.)*)"'
# `\` at a line's end inside a Rust string joins it to the next line's text, dropping the indentation.
def rust_string(raw: str) -> str:
    return re.sub(r"\\\n\s*", "", raw).replace('\\"', '"')

def strings(text: str) -> list[str]:
    return [rust_string(m) for m in re.findall(STRING, text, re.S)]

def ui_rules(source: str) -> dict[str, tuple[str, str]]:
    body = source[source.index("pub(super) fn ui_rule"):source.index("macro_rules! on_code")]
    rules: dict[str, tuple[str, str]] = {}
    arm = re.compile(r'^        "([a-z_.0-9]+)" => (.*?)(?=^        "[a-z_.0-9]+" =>|^        _ => return None)', re.S | re.M)
    for name, rest in arm.findall(body):
        rest = re.sub(r"^\s*//.*$", "", rest, flags=re.M)
        if "branch_rule" in rest:
            continue  # computed: added below from BRANCH_SOURCE
        found = strings(rest)
        if rest.lstrip("{ \n").startswith("p("):
            rules[name] = (found[0], found[1])
        elif len(found) == 1:
            rules[name] = (found[0], found[0])
        else:
            raise SystemExit(f"rules.rs: cannot read the rule of {name}: {rest[:60]!r}")
    return rules

def branch(source: str) -> str:
    src = re.search(r'const BRANCH_SOURCE: &str = "([^"]+)"', source).group(1)
    surfaces = "surface.window, surface.panel, surface.elevated"
    first = f"readable({src}, {surfaces}, mix(band.solid, {src}, 14%), 5)"
    return f"readable({src}, {surfaces}, mix(band.solid, {first}, 14%), 4.5)"

def main() -> int:
    source = SOURCE.read_text()
    rules = ui_rules(source)
    rules["git.branch"] = (branch(source), branch(source))
    code = "readable({}, terminal.background, diff.added.background, diff.removed.background, {})"
    table = source[source.index("pub(super) const SYNTAX_RULES"):]
    table = table[:table.index("];")]
    for key, rule in re.findall(r'\(\s*"([a-z_.]+)",\s*(.*?),\s*(?:true|false),\s*(?:true|false)\s*\)', table, re.S):
        m = re.match(r'on_code!\(\s*' + STRING + r',\s*' + STRING + r'\s*\)', rule, re.S)
        text = code.format(rust_string(m.group(1)), m.group(2)) if m else strings(rule)[0]
        rules["syntax." + key] = (text, text)
    metric = re.search(r"METRIC_RULES: &\[\(&str, &str\)\] = &\[(.*?)\];", source, re.S).group(1)
    for key, rule in re.findall(r'\("([a-z_]+)", "([a-z_]+)"\)', metric):
        rules["metrics." + key] = (rule, rule)

    lines = [
        "// Generated by apple/scripts/gen-token-rules.py from wormhole-core's theme/tokens/rules.rs: do not edit.",
        "// text-file: the core's token rule formulas (the theme file syntax), not interface text",
        "// Every token's default derivation rule, `(dark, light)`, in the expression syntax of themes.md.",
        "",
        "enum CoreRules {",
        "    static let table: [String: (dark: String, light: String)] = [",
    ]
    for name in sorted(rules):
        d, l = rules[name]
        esc = lambda s: s.replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'        "{name}": ("{esc(d)}", "{esc(l)}"),')
    lines += ["    ]", "}", ""]
    text = "\n".join(lines)
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("CoreRules.swift is stale: run apple/scripts/gen-token-rules.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    print(f"{len(rules)} rules written")
    return 0

if __name__ == "__main__":
    sys.exit(main())
