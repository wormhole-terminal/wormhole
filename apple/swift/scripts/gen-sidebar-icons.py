#!/usr/bin/env python3
"""Writes Sources/SidebarUI/Icons/AgentLogos.swift and Lucide.swift from the GPUI app's own SVGs
(crates/wormhole-core/assets/agent-icons/*.svg and gpui-kit-assets' Lucide icons), so the Swift sidebar draws the
same shapes. Rerun it when a logo changes; the output is checked in."""
import re, sys, pathlib

root = pathlib.Path(__file__).resolve().parents[3]
out = pathlib.Path(__file__).resolve().parents[1] / "Sources/SidebarUI/Icons"
logos = root / "crates/wormhole-core/assets/agent-icons"
lucide_dir = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else next(
    pathlib.Path.home().glob(".cargo/registry/src/*/gpui-kit-assets-0.8.0/assets/icons"))

def paths(svg):
    shapes = re.findall(r'<path[^>]*? d="([^"]+)"', svg)
    for x1, x2, y1, y2 in re.findall(r'<line x1="([^"]+)" x2="([^"]+)" y1="([^"]+)" y2="([^"]+)"', svg):
        shapes.append(f"M{x1} {y1}L{x2} {y2}")
    return shapes

def swift_list(shapes):
    return "[" + ", ".join('"' + s + '"' for s in shapes) + "]"

lines = ["// Generated by scripts/gen-sidebar-icons.py from crates/wormhole-core/assets/agent-icons: the agents' logos as SVG",
         "// path data in their 24-point box. `evenOdd` is the SVG's fill-rule, which the holes of some logos need.", "",
         "extension AgentLogo {",
         "    static let drawings: [String: (paths: [String], evenOdd: Bool)] = ["]
for svg in sorted(logos.glob("*.svg")):
    text = svg.read_text()
    lines.append(f'        "{svg.stem}": ({swift_list(paths(text))}, {"true" if "evenodd" in text else "false"}),')
lines += ["    ]", "}", ""]
(out / "AgentLogoData.swift").write_text("\n".join(lines))

lines = ["// Generated by scripts/gen-sidebar-icons.py from gpui-kit-assets' Lucide icons: the strokes the sidebar's marks use,",
         "// as SVG path data in their 24-point box (stroke width 2, round caps and joins).", "",
         "extension Lucide {",
         "    static let drawings: [Lucide: [String]] = ["]
for case, name in [("pin", "pin"), ("link", "link-2"), ("note", "sticky-note")]:
    lines.append(f'        .{case}: {swift_list(paths((lucide_dir / (name + ".svg")).read_text()))},')
lines += ["    ]", "}", ""]
(out / "LucideData.swift").write_text("\n".join(lines))
